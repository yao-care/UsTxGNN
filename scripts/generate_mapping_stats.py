#!/usr/bin/env python3
"""首頁 Statistics 表的 FDA 藥品數與 DrugBank 映射數（2026-11-05）：從 data/processed/drug_mapping.csv 算出來，
寫進 docs/_data/mapping_stats.json，首頁用 Liquid 讀（site.data.mapping_stats），不在頁面寫死。

來源：
    - data/processed/drug_mapping.csv：scripts/run_kg_prediction.py 產生，一列一個 FDA NDC Directory 產品
      （data/raw/us_fda_drugs.json，由 scripts/process_fda_data.py 從 https://www.accessdata.fda.gov/cder/ndctext.zip 產生）
    - fda_products：drug_mapping.csv 的列數（不含表頭）＝ NDC 產品數
    - drugbank_ids：mapping_success 為 True 的列裡，不重複的 drugbank_id 數
2026-11-05 前首頁寫死 104,047、1,667；依 Release data-20261029-223708 的 drug_mapping.csv 核對，數字相同。

data/ 不進 git（成果放 Release；還原見 scripts/restore_data.sh）。run_kg_prediction.py 跑完會自動呼叫本腳本；
也可單獨跑：uv run python scripts/generate_mapping_stats.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "processed" / "drug_mapping.csv"
OUT = ROOT / "docs" / "_data" / "mapping_stats.json"


def main() -> int:
    products = mapped_products = 0
    ids = set()
    with open(SRC, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            products += 1
            if str(r.get("mapping_success", "")).strip().lower() == "true" and r.get("drugbank_id"):
                mapped_products += 1
                ids.add(r["drugbank_id"].strip())
    if not products or not ids:
        raise SystemExit("drug_mapping.csv 是空的或沒有映射成功的列，不寫檔")
    data = {
        "_source": "US FDA NDC Directory (https://www.accessdata.fda.gov/cder/ndctext.zip), via scripts/process_fda_data.py "
                   "and scripts/run_kg_prediction.py: data/processed/drug_mapping.csv, one row per NDC product. "
                   "fda_products = rows; drugbank_ids = distinct drugbank_id among rows with mapping_success True. "
                   "Generated by scripts/generate_mapping_stats.py; do not edit.",
        "fda_products": products,
        "mapped_products": mapped_products,
        "drugbank_ids": len(ids),
        # Jekyll 3 的 Liquid 沒有千分位 filter，顯示用字串一起產生
        "display": {"fda_products": f"{products:,}", "drugbank_ids": f"{len(ids):,}"},
    }
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8")
        print(f"更新 {OUT.relative_to(ROOT)}：FDA 產品 {products:,}、DrugBank ID {len(ids):,}")
    else:
        print(f"{OUT.relative_to(ROOT)} 不變：FDA 產品 {products:,}、DrugBank ID {len(ids):,}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

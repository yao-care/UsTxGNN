#!/usr/bin/env python3
"""首頁 Statistics 表的 TxGNN 知識圖譜數字（2026-11-05）：從 data/external 的詞彙表算出來，寫進 docs/_data/kg_stats.json，
首頁用 Liquid 讀（site.data.kg_stats），不在頁面寫死。

來源（都由 scripts/prepare_external_data.py 從 TxGNN 的 node.csv、kg.csv 產生；node.csv／kg.csv 來自 Harvard Dataverse
doi:10.7910/DVN/IXA7BM）：
    - data/external/disease_vocab.csv：TxGNN 知識圖譜的疾病節點，一列一個疾病（不含表頭）
    - data/external/drug_disease_relations.csv：kg.csv 裡藥物–疾病的 indication 與 contraindication 邊，一列一條（不含表頭）
2026-11-05 前首頁寫死 17,081、80,127，是兩個檔的行數（多算了表頭那一行）；實際是 17,080 個疾病、80,126 條關係。

data/ 不進 git（成果放 Release；還原見 scripts/restore_data.sh）。prepare_external_data.py 跑完會自動呼叫本腳本；
也可單獨跑：uv run python scripts/generate_kg_stats.py
"""
import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXT = ROOT / "data" / "external"
OUT = ROOT / "docs" / "_data" / "kg_stats.json"


def main() -> int:
    with open(EXT / "disease_vocab.csv", encoding="utf-8", newline="") as f:
        diseases = sum(1 for _ in csv.DictReader(f))
    with open(EXT / "drug_disease_relations.csv", encoding="utf-8", newline="") as f:
        rel = Counter(r["relation"] for r in csv.DictReader(f))
    total = sum(rel.values())
    if not diseases or not total:
        raise SystemExit("詞彙表是空的，不寫檔")
    data = {
        "_source": "TxGNN knowledge graph (Harvard Dataverse doi:10.7910/DVN/IXA7BM), via scripts/prepare_external_data.py: "
                   "data/external/disease_vocab.csv (disease nodes) and data/external/drug_disease_relations.csv "
                   "(indication and contraindication edges). Generated by scripts/generate_kg_stats.py; do not edit.",
        "diseases": diseases,
        "drug_disease_relations": total,
        "relations_by_type": dict(sorted(rel.items())),
        # Jekyll 3 的 Liquid 沒有千分位 filter，顯示用字串一起產生
        "display": {"diseases": f"{diseases:,}", "drug_disease_relations": f"{total:,}"},
    }
    text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8")
        print(f"更新 {OUT.relative_to(ROOT)}：疾病 {diseases:,}、藥物–疾病關係 {total:,}")
    else:
        print(f"{OUT.relative_to(ROOT)} 不變：疾病 {diseases:,}、藥物–疾病關係 {total:,}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
